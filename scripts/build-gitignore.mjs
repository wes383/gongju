// Generates lib/gitignore-templates.ts from the upstream github/gitignore clone
// (expected at ./gitignore, CC0-1.0) plus lib/gitignore-catalog.json.
//
// Run after editing the catalogue: node scripts/build-gitignore.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(root, "lib/gitignore-catalog.json"), "utf8"));

/** Strip comments and blanks, trim trailing spaces, drop repeated lines. */
function cleanTemplate(text) {
  const seen = new Set();
  const patterns = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\s+$/, "");
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    if (seen.has(line)) continue;
    seen.add(line);
    patterns.push(line);
  }
  return patterns;
}

const templates = {};
const missing = [];

for (const group of catalog.groups) {
  const patterns = [];
  const seen = new Set();
  const push = (line) => {
    if (seen.has(line)) return;
    seen.add(line);
    patterns.push(line);
  };

  if (group.template) {
    const file = join(root, "gitignore", `${group.template}.gitignore`);
    if (existsSync(file)) {
      for (const line of cleanTemplate(readFileSync(file, "utf8"))) push(line);
    } else {
      missing.push(`${group.id} -> ${group.template}`);
    }
  }
  for (const line of group.patterns ?? []) push(line);

  if (patterns.length === 0) {
    throw new Error(`group "${group.id}" has no patterns`);
  }
  templates[group.id] = patterns;
}

const entries = Object.entries(templates).map(([id, list]) => {
  const key = /^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id);
  const body = list.map((pattern) => `    ${JSON.stringify(pattern)}`).join(",\n");
  return `  ${key}: [\n${body}\n  ]`;
});

const out = `// AUTO-GENERATED by scripts/build-gitignore.mjs — do not edit by hand.
// Sources: https://github.com/github/gitignore (CC0-1.0) + lib/gitignore-catalog.json
export const GITIGNORE_TEMPLATES: Record<string, string[]> = {
${entries.join(",\n")}
};
`;

writeFileSync(join(root, "lib/gitignore-templates.ts"), out);

const total = Object.values(templates).reduce((sum, list) => sum + list.length, 0);
console.log(`wrote ${Object.keys(templates).length} groups, ${total} patterns`);
if (missing.length) {
  console.warn(`missing upstream templates:\n  ${missing.join("\n  ")}`);
}
