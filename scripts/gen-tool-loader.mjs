/**
 * Regenerates components/tools/tool-loader.tsx, the slug → lazy component map
 * used by the /zh/tools/[slug] catch-all. Run from the repo root after adding
 * or renaming a tool: node scripts/gen-tool-loader.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const toolsDir = resolve(process.cwd(), "app/(en)/tools");
const entries = [];

for (const slug of readdirSync(toolsDir).sort()) {
  const source = readFileSync(resolve(toolsDir, slug, "page.tsx"), "utf8");
  const imports = [...source.matchAll(/import \{ (\w+) \} from "@\/components\/tools\/([^"]+)";/g)];
  const match = imports.find(([, , file]) => !file.startsWith("tool-"));
  if (!match) throw new Error(`no tool component import found in ${slug}/page.tsx`);
  const [, component, file] = match;
  entries.push(
    `  ${JSON.stringify(slug)}: dynamic(() => import("./${file}").then((m) => m.${component})),`
  );
}

const out = `"use client";

import type { ComponentType } from "react";
import dynamic from "next/dynamic";

/** Generated by scripts/gen-tool-loader.mjs — rerun after adding a tool */
const TOOLS: Record<string, ComponentType> = {
${entries.join("\n")}
};

export function ToolLoader({ slug }: { slug: string }) {
  const Tool = TOOLS[slug];
  return Tool ? <Tool /> : null;
}
`;

writeFileSync(resolve(process.cwd(), "components/tools/tool-loader.tsx"), out);
console.log(`tool-loader: ${entries.length} tools`);